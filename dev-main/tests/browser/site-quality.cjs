/* Focused regressions: browser Back, working navigation and answer clipboard. */
const {chromium, devices} = require('playwright');
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const STATIC = path.resolve(__dirname, '../../static');

(async () => {
  const browser = await chromium.launch({executablePath:process.env.CHROMIUM_PATH || '/usr/bin/chromium', args:['--no-sandbox']});
  const context = await browser.newContext({...devices['Pixel 7'], permissions:['clipboard-read','clipboard-write']});
  const answer = '**Чернозём** богат гумусом [M1].\n\nИсточники:\n[M1] Музей — https://example.org/soil_data';
  await context.route('https://quality.test/**', route => {
    const p = new URL(route.request().url()).pathname;
    const reply = (data,status=200) => route.fulfill({status,contentType:'application/json',body:JSON.stringify(data)});
    if (p === '/me') return reply({detail:'Войдите'},401);
    if (p === '/ask/jobs') return reply({job_id:'job',conversation_id:'c'.repeat(43),status:'queued',ahead:0},202);
    if (p.startsWith('/conversations/')) return reply({conversation_id:'c'.repeat(43),turns:[{question:'Расскажи о чернозёме',answer,has_image:false}],active_job_id:null});
    if (p === '/ask/jobs/job') return reply({job_id:'job',conversation_id:'c'.repeat(43),status:'done',answer,ahead:0});
    const file = path.join(STATIC, p === '/' ? 'index.html' : p);
    return fs.existsSync(file)&&fs.statSync(file).isFile()?route.fulfill({path:file}):route.fulfill({status:404,body:''});
  });
  const page = await context.newPage();const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('https://quality.test/');await page.waitForFunction(()=>document.documentElement.dataset.chatReady==='true');
  assert.equal(await page.locator('.sidebar a[href="/#ai-chat"]').getAttribute('aria-current'),'location');
  assert.equal(await page.locator('.sidebar .nav-item:not(a)').count(),0);
  assert.equal(await page.locator('.copy-answer').count(),0,'welcome is not a generated answer');
  await page.locator('.mobile-section-nav a[href="#catalog"]').tap();
  assert.equal(await page.locator('.sidebar a[href="/#catalog"]').getAttribute('aria-current'),'location');
  await page.locator('#catalog-search').fill('Грузия');
  assert.equal(await page.locator('.soil-card:visible').count(),1);
  await page.locator('.mobile-chat-link').tap();
  await page.locator('.mobile-section-nav a[href="#catalog"]').tap();
  await page.locator('#catalog-search').fill('чернозём');
  assert((await page.locator('.soil-card:visible').count())>1);
  await page.goBack();await page.goBack();
  assert.equal(await page.locator('#catalog-search').inputValue(),'Грузия');
  assert.equal(await page.locator('.soil-card:visible').count(),1);
  assert.equal(await page.locator('.soil-card:visible').getAttribute('href'),'/soils/029/');
  await page.goto('https://quality.test/?limit=12.5#catalog');
  assert.equal(await page.locator('.soil-card:visible').count(),12);
  assert((await page.locator('#catalog-count').textContent()).startsWith('Показано 12 из'));
  await page.locator('.mobile-chat-link').tap();
  await page.waitForFunction(()=>document.documentElement.dataset.chatReady==='true');
  await page.locator('#chat-input').fill('Расскажи о чернозёме');await page.locator('#send-btn').tap();
  const copy = page.locator('.copy-answer');await copy.waitFor();await copy.tap();
  await page.locator('.copy-status').filter({hasText:'Скопировано'}).waitFor();
  assert.equal(await page.evaluate(()=>navigator.clipboard.readText()),answer,'clipboard retains source URLs and full answer');
  await page.evaluate(()=>{navigator.clipboard.writeText=async()=>{throw Error('Permission denied')};});
  await copy.tap();await page.locator('.copy-status').filter({hasText:'Не удалось скопировать'}).waitFor();
  assert.equal(await copy.isEnabled(),true);
  await page.reload();await page.locator('.copy-answer').waitFor();
  await page.locator('.copy-answer').tap();
  await page.locator('.copy-status').filter({hasText:'Скопировано'}).waitFor();
  assert.equal(await page.evaluate(()=>navigator.clipboard.readText()),answer,'restored answers are also copyable');
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  assert.deepEqual(errors,[]);
  console.log('PASS working nav / active section / Back restores filters / integer limit / copy with sources / clipboard denial');
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1);});
