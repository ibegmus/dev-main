"""Interview guidance, not a trained soil classifier or a laboratory diagnosis."""
import re

def identification_request(question):
    text=question.casefold()
    # A question about working with soil is not a request to identify its type.
    # Keep explicit mixed requests, including "как измерить pH и определить тип".
    how_to=re.search(r'\b(?:как|чем|зачем|почему|сколько|когда)\b|\bчто такое\b|\b(?:можно|нужно) ли\b',text)
    direct_type=re.search(r'(?:определ\w*|распозна\w*)\s+(?:(?:тип|вид|название)\s+)?(?:почв|грунт|земл)',text)
    named_type=re.search(r'(?:определ\w*|распозна\w*|что за).{0,40}(?:тип|вид|название)\s+(?:почв|грунт|земл)',text)
    if how_to and not (direct_type or named_type):return False
    explicit=re.search(r'(?:определ\w*|распозна\w*|что за).{0,60}(?:почв|грунт|земл)',text)
    site=re.search(r'у меня|на (?:участке|даче|фото|снимке)|какая (?:это|эта)|какой (?:это|этот)',text)
    return bool(explicit or (site and re.search(r'почв|грунт|земл',text)))

